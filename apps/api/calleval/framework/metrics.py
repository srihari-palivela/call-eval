# Dimensions, metrics and compliance gates of the Call Evaluation Framework v1.
# Every metric carries its normalisation rule, so a raw measurement turns into a 0–100 score the
# same way in the pipeline, the scoring model screen and the tests.
#
# Norm kinds: pass (1 or 0), low (lower is better: 100 at or under green, 0 at or over red),
# high (higher is better), two (two-sided band), judge (a judge scale rescaled to 0–100).
# `weight` 2 marks Re-ask and Wrong path, which count twice; `needsAudio` metrics drop out without
# a usable recording; `rubric` is the line the judge scores against.

